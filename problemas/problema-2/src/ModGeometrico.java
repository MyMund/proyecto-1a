    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        /*
            Obtiene las cuatro coordenadas, calcula sus incrementos y aplica
            el teorema de Pitágoras para determinar la distancia entre P1 y P2.
            Si algún campo no contiene un número válido, informa al usuario.
        */
        //Esta parte es la que se encarga de validar los campos que se ingresen.
        try {
            //Obtiene y convierte las coordenadas de tipo String a Double que se ingresan en el formulario.
            double x1 = Double.parseDouble(inputX1.getText().trim());
            double y1 = Double.parseDouble(inputY1.getText().trim());
            double x2 = Double.parseDouble(inputX2.getText().trim());
            double y2 = Double.parseDouble(inputY2.getText().trim());

            //Calcula cada incremento en X y Y.
            double incrementoX = x2 - x1;
            double incrementoY = y2 - y1;

            //Eleva al cuadrado cada uno de los incrementos.
            double incrementoXCu = Math.pow(incrementoX, 2);
            double incrementoYCu = Math.pow(incrementoY, 2);

            //Sumar ambos cuadrados
            double sumaCuadrados = incrementoXCu + incrementoYCu;

            //Extrae la raíz cuadrada para obtener la distancia.
            double distancia = Math.sqrt(sumaCuadrados);

            //Muestra los resultados en las etiquetas de salida dando un formato para que solo se muestren dos decimales.
            salidaIncrementoX.setText("Incremento en X (Δx): " + formatearNumero(incrementoX));
            salidaIncrementoY.setText("Incremento en Y (Δy): " + formatearNumero(incrementoY));
            resultado.setText(formatearNumero(distancia) + " u");   
            
          //En caso de que los valores ingresados en los campos no sean validos, se le avisa al usuario  
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Por favor ingresa valores numéricos válidos en las cuatro coordenadas (x1, y1, x2, y2).",
                "Dato inválido o vacío",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

