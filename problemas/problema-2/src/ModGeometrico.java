    /*
    Método reutilizable para validar en tiempo real los 4 campos de coordenadas.
    Permite: dígitos (0-9), un único punto decimal (.) y el signo negativo (-)
    únicamente al inicio del campo (posición 0) siempre que no exista otro signo menos.
    */
    private void validarCoordenada(java.awt.event.KeyEvent evt, javax.swing.JTextField campo) {
        /*
            Valida cada coordenada mientras se escribe. Permite números,
            un punto decimal, notación científica y el signo negativo
            únicamente en posiciones válidas.
        */
        char c = evt.getKeyChar();
        String textoActual = campo.getText();
        int pos = campo.getCaretPosition();

        // 1. Permitir teclas de control (Backspace, Delete, etc.)
        if (Character.isISOControl(c)) {
            aviso.setText("");
            return;
        }

        // 2. Permitir 'e' o 'E' para notación científica (solo una vez y después de algún dígito)
        if (c == 'e' || c == 'E') {
            if (!textoActual.toLowerCase().contains("e") && pos > 0 && textoActual.matches(".*\\d.*")) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("Uso inválido de notación científica (ej. 1.34e154).");
            }
            return;
        }

        // 3. Permitir '-' al inicio (posición 0) O justo después de 'e'/'E' (ej. 1e-5)
        if (c == '-') {
            boolean alInicio = (pos == 0 && !textoActual.startsWith("-"));
            boolean trasExponente = (pos > 0 && (textoActual.charAt(pos - 1) == 'e' || textoActual.charAt(pos - 1) == 'E'));

            if (alInicio || trasExponente) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("El signo (-) solo va al inicio o después de 'e'.");
            }
            return;
        }

        // 4. Permitir un único punto decimal '.' (y solo antes de la 'e')
        if (c == '.') {
            if (!textoActual.contains(".") && !textoActual.toLowerCase().contains("e")) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("Punto decimal inválido o duplicado.");
            }
            return;
        }

        // 5. Bloquear cualquier otra letra o símbolo que no sea dígito (0-9)
        if (!Character.isDigit(c)) {
            evt.consume();
            aviso.setText("Ingresa solo números válidos (ej. -4.5, 1.34e154).");
        } else {
            aviso.setText("");
        }
    }

    private void bloquearPegado(javax.swing.JTextField campo, javax.swing.JLabel lblAviso) {
        /*
            Deshabilita la operación de pegar en los campos de coordenadas
            para que los datos se introduzcan mediante el teclado.
        */
        campo.setTransferHandler(new javax.swing.TransferHandler("text") {
            @Override
            public boolean importData(javax.swing.TransferHandler.TransferSupport support) {
                if (lblAviso != null) {
                    lblAviso.setText("No se permite pegar texto en este campo.");
                }
                return false;
            }
        });
    }
    
