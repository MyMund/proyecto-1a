    /*
    Formatea un valor double para su visualización limpia en pantalla:
    - Si es infinito, muestra "Infinity".
    - Si su magnitud es muy grande (>= 1 billón), usa notación científica (ej. 1.3400e+154).
    - En cualquier caso habitual, lo muestra con 2 decimales estándar.
    */
    private String formatearNumero(double valor) {
        if (Double.isInfinite(valor)) {
            return "Infinity";
        }
        if (Math.abs(valor) >= 1e12) {
            return String.format("%.4e", valor);
        }
        return String.format("%.2f", valor);
    }
    
    
