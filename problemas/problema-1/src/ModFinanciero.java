    private void estilizarBoton(javax.swing.JButton boton, java.awt.Color colorFondo, java.awt.Color colorHover, java.awt.Color colorTexto) {
        boton.setBackground(colorFondo);
        boton.setForeground(colorTexto);
        boton.setFocusPainted(false);
        boton.setBorderPainted(false);
        boton.setContentAreaFilled(false);
        boton.setOpaque(true);
        boton.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));

        boton.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseEntered(java.awt.event.MouseEvent e) {
                boton.setBackground(colorHover);
            }

            @Override
            public void mouseExited(java.awt.event.MouseEvent e) {
                boton.setBackground(colorFondo);
            }

            @Override
            public void mousePressed(java.awt.event.MouseEvent e) {
                boton.setBackground(colorFondo.darker());
            }

            @Override
            public void mouseReleased(java.awt.event.MouseEvent e) {
                boton.setBackground(boton.contains(e.getPoint()) ? colorHover : colorFondo);
            }
        });
    }
    /*
    Método encargado de impedir que el usuario pegue contenido desde el portapapeles
    (mediante Ctrl+V, Shift+Insert o clic derecho) en un JTextField específico,
    conservando intacta la capacidad de seleccionar y copiar texto hacia afuera.
    */
    private void bloquearPegado(javax.swing.JTextField campo, javax.swing.JLabel lblAviso) {
        /*
        Se asigna un nuevo TransferHandler configurado con la propiedad "text" para
        mantener el soporte nativo de exportación (copiar/cortar), pero sobrescribiendo
        la recepción de datos entrantes.
        */
        campo.setTransferHandler(new javax.swing.TransferHandler("text") {
            
            /*
            El método importData se ejecuta automáticamente cada vez que el componente
            recibe datos externos (como pegar desde el portapapeles o arrastrar texto).
            Al devolver false, se rechaza la inserción y el texto no se pega.
            */
            @Override
            public boolean importData(javax.swing.TransferHandler.TransferSupport support) {
                // Verifica que exista una etiqueta de aviso asignada y muestra la advertencia.
                if (lblAviso != null) {
                    lblAviso.setText("No se permite pegar texto en este campo.");
                }
                // Retorna false para cancelar por completo la operación de pegado.
                return false;
            }
        });
    }
    
