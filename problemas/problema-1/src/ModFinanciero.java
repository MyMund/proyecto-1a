    private void evaluarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_evaluarActionPerformed

        /*
        Se utiliza un bloque try-catch para capturar posibles errores de formato
        en caso de que el usuario deje el campo del precio vacío o escriba letras
        en lugar de un valor numérico válido.
        */
        try {
            /*
            Obtiene el texto ingresado en el campo del precio, elimina espacios
            en blanco al inicio y al final con .trim(), y lo convierte a tipo double.
            */
            double precioBase = Double.parseDouble(txtPrecio.getText().trim());

            /*
            Valida que el precio ingresado no sea un número negativo. Si lo es,
            muestra una ventana de advertencia y detiene la ejecución del método con return.
            */
            if (precioBase < 0) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El precio no puede ser negativo. Ingresa un monto mayor o igual a 0.",
                    "Precio inválido",
                    javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            /*
            Revisa si las casillas de P y Q estan marcadas, 
            en caso de ser verdadero: P y/o Q seran verdaderos (true),
            caso contrario seran falsos (false).
            */
            boolean p = premisaP.isSelected();
            boolean q = premisaQ.isSelected();

            /* 
            Las lineas funcionan como si fueran un if - else
            resumido en una sola linea conocido como operador ternario,
            si P y/o Q son verdaderos se les asigna el valor de 1,
            en caso de que no se les asigna el valor de 0.
            Además de mostrar los valores en la pantalla.
            */
            int P = p ? 1 : 0;
            int Q = q ? 1 : 0;
            salidaValores.setText("Valores: p = " + P + " , q = " + Q);

            /*
            Variable auxiliar que almacenará la tasa porcentual en formato decimal
            (0.00, 0.08 o 0.16) para realizar la operación aritmética posterior.
            */
            double tasaImpuesto;

            /*
            Dependiendo de que condicion lógica se cumpla se asigna la tasa de impuesto
            y se muestra en pantalla tanto el porcentaje, el estado, un color distintivo 
            y que fórmula se aplica.
            */
            if (p && q) {
                //Regla 1: Exención Total (En caso de que ambas proposiciones se cumplan).
                tasaImpuesto = 0.00;
                salidaPorcentaje.setText("0%");
                salidaPorcentaje.setForeground(new java.awt.Color(20, 150, 127));
                proposiciones.setText("Exención Total de Impuesto");
                salidaFormula.setText("Fórmula aplicada: p && q (AND)");

            } else if (p || q) {
                /*
                Regla 2: Impuesto Subvencionado / Reducido (En caso de que se cumpla 
                una de las dos proposiciones, pero no las dos al mismo tiempo).
                */
                tasaImpuesto = 0.08;
                salidaPorcentaje.setText("8%");
                salidaPorcentaje.setForeground(new java.awt.Color(232, 146, 26));
                proposiciones.setText("Impuesto Subvencionado / Reducido");
                salidaFormula.setText("Fórmula aplicada: p || q (OR)");

            } else {
                //Regla 3: Impuesto General Standard (En caso de que ninguna proposición se cumpla).
                tasaImpuesto = 0.16;
                salidaPorcentaje.setText("16%");
                salidaPorcentaje.setForeground(new java.awt.Color(200, 55, 55));
                proposiciones.setText("Impuesto General Standard");
                salidaFormula.setText("Fórmula aplicada: ¬p && ¬q (NOT)");
            }

            /*
            Calcula el monto del impuesto multiplicando el precio base por la tasa
            correspondiente, y obtiene el total sumando ambos valores.
            */
            double montoImpuesto = precioBase * tasaImpuesto;
            double totalPagar = precioBase + montoImpuesto;

            /*
            Muestra los resultados monetarios en las etiquetas de salida formateados
            a exactamente 2 decimales con String.format.
            */
            salidaImpuesto.setText("Impuesto calculado: $" + formatearNumero(montoImpuesto));
            salidaTotal.setText("Total a pagar: $" + formatearNumero(totalPagar));

        } catch (NumberFormatException e) {
            /*
            En caso de ocurrir una excepción al convertir el texto a número, se muestra
            un mensaje de advertencia al usuario y se devuelve el cursor al campo de precio.
            */
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Por favor ingresa un precio numérico válido (ejemplo: 1500.00).",
                "Dato inválido o vacío",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            txtPrecio.requestFocus();
        }
    }//GEN-LAST:event_evaluarActionPerformed

