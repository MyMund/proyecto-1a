    private void txtPrecioKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPrecioKeyTyped
        char c = evt.getKeyChar();
        String textoActual = txtPrecio.getText();
        int pos = txtPrecio.getCaretPosition();

        // 1. Permitir teclas de control (Backspace, Delete, etc.)
        if (Character.isISOControl(c)) {
            aviso.setText("");
            return;
        }

        // 2. Permitir 'e' o 'E' para notación científica (solo una vez y después de algún dígito)
        if (c == 'e' || c == 'E') {
            if (!textoActual.toLowerCase().contains("e") && pos > 0 && textoActual.matches(".*\\d.*")) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("Uso inválido de notación científica (ej. 1.6e308).");
            }
            return;
        }

        // 3. Permitir '-' únicamente después de 'e' o 'E' (ej. 1.5e-4), bloqueándolo al inicio
        if (c == '-') {
            boolean trasExponente = (pos > 0 && (textoActual.charAt(pos - 1) == 'e' || textoActual.charAt(pos - 1) == 'E'));
            if (trasExponente) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("El precio no puede ser negativo; '-' solo va tras 'e'.");
            }
            return;
        }

        // 4. Permitir un único punto decimal '.' (y solo antes de la 'e')
        if (c == '.') {
            if (!textoActual.contains(".") && !textoActual.toLowerCase().contains("e")) {
                aviso.setText("");
            } else {
                evt.consume();
                aviso.setText("Punto decimal inválido o duplicado.");
            }
            return;
        }

        // 5. Bloquear cualquier otra letra o símbolo que no sea dígito (0-9)
        if (!Character.isDigit(c)) {
            evt.consume();
            aviso.setText("Ingresa solo precios válidos (ej. 1500.50, 1.6e308).");
        } else {
            aviso.setText("");
        }
    }//GEN-LAST:event_txtPrecioKeyTyped

